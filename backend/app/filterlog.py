"""pfSense / OPNsense ``filterlog`` parser.

Both firewalls log every pf rule hit as one CSV line (pfSense documents the
format under "Filter Log Format", OPNsense uses the same layout):

    common:  rule, subrule, anchor, tracker|label, real-iface, reason, action, dir, ip-ver
    IPv4:    tos, ecn, ttl, id, offset, flags, proto-id, proto-text, length, src, dst
    IPv6:    class, flow-label, hop-limit, proto-text, proto-id, length, src, dst
    then:    tcp:  sport, dport, data-len, flags, seq, ack, window, urg, options
             udp:  sport, dport, data-len
             icmp: type, type-specific fields...
             carp: type, ttl, vhid, version, advbase, advskew

On pfSense field 4 is the rule's numeric *tracker* id (the number shown in
brackets in Status > System Logs > Firewall); on OPNsense it is the rule's
32-character hex *label* (rid). Either way it is what we resolve to a rule
description.

Pure functions only, so this is easy to unit test.
"""

from __future__ import annotations

import ipaddress
from dataclasses import asdict, dataclass
from functools import lru_cache
from typing import Any

ACTIONS = ("pass", "block", "reject", "match", "scrub", "rdr", "nat", "binat")

# pfSense's built-in rules have fixed tracker ids (they are generated by filter.inc, not stored in config.xml,
# so the REST API cannot list them). Only the well-known ones are named; other 10000000xx ids are "system rule".
SYSTEM_RULES: dict[str, str] = {
    "1000000003": "Block all IPv6",
    "1000000103": "Default deny rule IPv4",
    "1000000104": "Default deny rule IPv6",
    "11000": "Block bogon networks",
    "12000": "Block private networks",
}

# Packets nobody wants to scroll through: mDNS/SSDP/LLMNR/NDP chatter to multicast and broadcast.
_NOISE_NETS = [ipaddress.ip_network(n) for n in ("224.0.0.0/4", "255.255.255.255/32", "ff00::/8")]


@dataclass
class FilterLogEvent:
    action: str  # pass | block | reject | match ...
    direction: str  # in | out
    iface: str  # real interface (igb0.20, vtnet1 ...)
    rule_id: str  # pfSense tracker id / OPNsense rule label
    rule_number: str
    reason: str
    ipver: int
    proto: str  # tcp | udp | icmp | ipv6-icmp | carp | igmp ...
    src: str
    dst: str
    sport: int | None = None
    dport: int | None = None
    length: int | None = None
    tcp_flags: str = ""
    info: str = ""  # icmp type, carp vhid ... whatever is protocol specific

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def _int(v: str) -> int | None:
    v = v.strip()
    return int(v) if v.isdigit() else None


@lru_cache(maxsize=65536)
def canonical_ip(ip: str) -> str | None:
    """Compressed canonical form (or None if not an IP)."""
    try:
        return str(ipaddress.ip_address(ip.strip()))
    except ValueError:
        return None


@lru_cache(maxsize=65536)
def ip_key(ip: str) -> str:
    """32 hex chars that sort like the address: IPv4 as ::ffff:a.b.c.d, so a CIDR becomes a string range."""
    try:
        addr = ipaddress.ip_address(ip.strip())
    except ValueError:
        return ""
    if addr.version == 4:
        addr = ipaddress.IPv6Address(f"::ffff:{addr}")
    return f"{int(addr):032x}"


def cidr_key_range(cidr: str) -> tuple[str, str] | None:
    """'10.10.20.0/24' -> (lowest key, highest key); a bare IP gives a one-address range."""
    try:
        net = ipaddress.ip_network(cidr.strip(), strict=False)
    except ValueError:
        return None
    lo, hi = net.network_address, net.broadcast_address
    if net.version == 4:
        lo, hi = ipaddress.IPv6Address(f"::ffff:{lo}"), ipaddress.IPv6Address(f"::ffff:{hi}")
    return f"{int(lo):032x}", f"{int(hi):032x}"


@lru_cache(maxsize=65536)
def is_noise(src: str, dst: str) -> bool:
    """Multicast / broadcast / IPv6 link-local chatter (mDNS, SSDP, NDP, DHCPv6 solicit ...)."""
    try:
        d = ipaddress.ip_address(dst)
        s = ipaddress.ip_address(src)
    except ValueError:
        return False
    if any(d in n for n in _NOISE_NETS if n.version == d.version):
        return True
    return s.version == 6 and s.is_link_local and d.is_link_local


def strip_tag(message: str) -> str:
    """Accept both the bare CSV and "filterlog[123]: <csv>" when the syslog tag was not split off."""
    msg = message.strip()
    if msg[:1].isdigit():
        return msg
    _, sep, rest = msg.partition(": ")
    return rest.strip() if sep else msg


def looks_like_filterlog(app: str, message: str) -> bool:
    if "filterlog" in (app or "").lower():
        return True
    head = message[:120]
    return head[:1].isdigit() and (",match," in head or ",block," in head or ",pass," in head) and head.count(",") >= 8


def parse(message: str) -> FilterLogEvent | None:
    """Parse one filterlog line; ``None`` when it is not a (supported) filterlog record."""
    f = strip_tag(message).split(",")
    if len(f) < 10:
        return None
    action, direction, ver = f[6].strip().lower(), f[7].strip().lower(), f[8].strip()
    if action not in ACTIONS:
        return None
    if ver == "4" and len(f) >= 20:
        proto, length, src, dst, rest = f[16].strip().lower(), _int(f[17]), f[18], f[19], f[20:]
        if not proto and f[15].strip().isdigit():
            proto = f[15].strip()
    elif ver == "6" and len(f) >= 17:
        proto, length, src, dst, rest = f[12].strip().lower(), _int(f[14]), f[15], f[16], f[17:]
        if not proto and f[13].strip().isdigit():
            proto = f[13].strip()
    else:
        return None
    src_c, dst_c = canonical_ip(src), canonical_ip(dst)
    if not src_c or not dst_c:
        return None
    ev = FilterLogEvent(action=action, direction=direction, iface=f[4].strip(), rule_id=f[3].strip() or "",
                        rule_number=f[0].strip(), reason=f[5].strip(), ipver=int(ver), proto=proto or "?",
                        src=src_c, dst=dst_c, length=length)
    if proto in ("tcp", "udp", "sctp") and len(rest) >= 2:
        ev.sport, ev.dport = _int(rest[0]), _int(rest[1])
        if proto == "tcp" and len(rest) >= 4:
            ev.tcp_flags = rest[3].strip()
    elif proto in ("icmp", "ipv6-icmp", "icmp6", "icmpv6") and rest:
        ev.info = ",".join(x.strip() for x in rest[:3] if x.strip())[:64]
    elif proto == "carp" and len(rest) >= 3:
        ev.info = f"vhid {rest[2].strip()}"
    return ev


def rule_label(rule_id: str, rules: dict[str, str] | None = None) -> str:
    """Human rule name for a tracker/label: device rules first, then pfSense's built-ins."""
    if not rule_id:
        return ""
    if rules and (d := rules.get(rule_id)):
        return d
    if rule_id in SYSTEM_RULES:
        return SYSTEM_RULES[rule_id]
    if len(rule_id) == 10 and rule_id.startswith("10000") and rule_id.isdigit():
        return "System rule"
    return ""
